def install_base(venv_dir: Path, wheel: Path) -> None:
    pip_install(venv_dir, str(wheel))


def install_extra(venv_dir: Path, wheel: Path, extra: str, dist_dir: Path) -> None:
    pip_install(venv_dir, "--find-links", str(dist_dir), f"dbfbridge[{extra}]")


def assert_base_contract(venv_dir: Path, wheel: Path, expected_version: str) -> None:
    code = (
        "import json, importlib.metadata, sys\n"
        "import dbfbridge\n"
        f"assert dbfbridge.__version__ == {expected_version!r}, dbfbridge.__version__\n"
        "import dbf_bridge\n"
        f"assert dbf_bridge.__version__ == {expected_version!r}\n"
        "installed = sorted({d.metadata['Name'].lower() for d in importlib.metadata.distributions()})\n"
        f"forbidden = {list(REQUIRED_BASE_ABSENT)!r}\n"
        "present = [name for name in forbidden if name in installed]\n"
        "assert not present, ('mandatory deps leaked into base install:', present)\n"
        "heavy = [m for m in ('dbf','dbfread','orjson','polars','openpyxl','xlsxwriter') if m in sys.modules]\n"
        "assert heavy == [] or heavy == ['dbfread'], heavy\n"
        "print(json.dumps({'version': dbfbridge.__version__, 'origin': dbfbridge.__file__, 'installed': installed}))\n"
    )
    out = snippet(venv_dir, code)
    payload = json.loads(out.strip().splitlines()[-1])
    if "site-packages" not in payload["origin"].replace("\\", "/"):
        raise SmokeFailure(f"dbfbridge did not come from the fresh venv: {payload['origin']}")
    print(f"  version={payload['version']} origin-in-venv=True base-inventory-clean=True")
    assert "dbfread" in payload["installed"], payload["installed"]


def direct_read_smoke(venv_dir: Path, fixture: Path, work: Path) -> None:
    fixture_posix = str(fixture).replace("\\", "/")
    code = f"""
import json, sys
from pathlib import Path
from dbfbridge import (
    inspect_table, read_schema, iter_records, read_records, iter_raw_records,
)

source = r"{fixture_posix}"

info = inspect_table(source)
assert info.record_count == 200, info.record_count
assert len(info.fields) == 4, len(info.fields)

schema = read_schema(source)
assert schema.record_count == 200

records = iter_records(source, memo="skip")
count = 0
try:
    for index, record in enumerate(records):
        count += 1
        if index == 9:
            break
finally:
    records.close()
assert count == 10, count

page = read_records(source, offset=0, limit=100)
assert len(page.records) == 100 and page.next_offset == 100

raw_total = sum(1 for _ in iter_raw_records(source))
assert raw_total == 200, raw_total

assert not list(Path(r"{work.as_posix()}").glob("**/*.partial"))
print("direct-read OK")
"""
    snippet(venv_dir, code, cwd=work)


def migration_smoke(venv_dir: Path, fixture: Path, work: Path) -> None:
    code = f"""
import json
from pathlib import Path
from dbfbridge import export_dbf

out = Path("migration_out")
result = export_dbf(r"{str(fixture).replace(chr(92), "/")}", str(out), formats=("jsonl", "json", "csv"))
result.raise_for_errors()
for name in ("customers.jsonl", "customers.json", "customers.csv"):
    assert (out / name).is_file(), name
rows = [json.loads(line) for line in (out / "customers.jsonl").read_text(encoding="utf-8").splitlines() if line.strip()]
assert len(rows) == 200, len(rows)
print("migration OK")
"""
    snippet(venv_dir, code, cwd=work)


def negative_write_smoke(venv_dir: Path, export_dir: Path, work: Path) -> None:
    code = f"""
import json
from pathlib import Path
from dbfbridge import OptionalDependencyMissingError, reconstruct_dbf

out = Path("negative_write_out")
try:
    reconstruct_dbf(r"{str(export_dir).replace(chr(92), "/")}", str(out), input_format="jsonl")
except OptionalDependencyMissingError as error:
    payload = error.to_dict()
    assert payload["code"] == "OPTIONAL_DEPENDENCY_MISSING", payload
    assert payload["dependency"] == "dbf" and payload["extra"] == "write", payload
    assert payload["install_command"] == 'python -m pip install "dbfbridge[write]"', payload
else:
    raise SystemExit("reconstruct_dbf must fail without [write]")
assert not out.exists(), "zero output artifacts required"
print("negative-write OK")
"""
    snippet(venv_dir, code, cwd=work)


