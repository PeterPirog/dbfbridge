def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--wheel", type=Path, default=None, help="existing feature wheel to test")
    parser.add_argument("--expected-version", default=None, help="assert the wheel version")
    parser.add_argument(
        "--keep-temp", action="store_true", help="keep the temporary work directory"
    )
    args = parser.parse_args(argv)

    wheel = args.wheel
    if wheel is None:
        dist = REPO_ROOT / "dist"
        wheels = sorted(dist.glob("dbfbridge-*.whl"))
        if not wheels:
            raise SmokeFailure("no wheel given and none found in dist/ (run `python -m build`)")
        wheel = wheels[-1]
    wheel = wheel.resolve()
    expected_version = args.expected_version or _wheel_version(wheel)

    work_root = Path(tempfile.mkdtemp(prefix="dbfbridge-pypi-smoke-"))
    dist_dir = wheel.parent
    try:
        print(f"wheel: {wheel}")
        print(f"expected version: {expected_version}")
        fixtures = prepare_fixtures(work_root)
        print(f"fixtures: {sorted(str(value) for value in fixtures.values())}")

        # 1) base install contract
        base = build_fresh_venv(work_root, "venv-base")
        install_base(base, wheel)
        assert_base_contract(base, wheel, expected_version)

        # 2) Direct Read on the base install (incl. REAL Mazovia bytes +
        # exact-text verification with the installed wheel)
        direct_read_contract_smoke(
            base,
            fixtures["flat"],
            work_root,
            mazovia_fixture=fixtures["mazovia_real"],
            mazovia_sidecar=fixtures["mazovia_sidecar"],
        )

        # 3) base migration (JSONL/JSON/CSV with fallbacks)
        migration_smoke(base, fixtures["flat"], work_root)

        # prepare export inputs with the base venv (export needs no [write])
        def _export(source_dbf: Path, formats: list[str], name: str) -> Path:
            out = work_root / name
            code = (
                "from pathlib import Path\n"
                "from dbfbridge import export_dbf\n"
                f'result = export_dbf(r"{source_dbf.as_posix()}", r"{out.as_posix()}", formats={formats!r}, overwrite=True)\n'
                "result.raise_for_errors()\n"
                "print('exported')\n"
            )
            snippet(base, code, cwd=work_root)
            return out

        export_jsonl = _export(fixtures["flat"], ["jsonl"], "export-jsonl")
        export_memo_jsonl = _export(fixtures["memo"], ["jsonl"], "export-memo-jsonl")

        # 4) negative smokes on the base install
        negative_write_smoke(base, export_jsonl, work_root)
        negative_xlsx_smoke(base, fixtures["flat"], work_root)

        # 5) [write]
        venv_write = build_fresh_venv(work_root, "venv-write")
        install_extra(venv_write, wheel, "write", dist_dir)
        write_extra_smoke(venv_write, export_jsonl, work_root)
        write_memo_extra_smoke(venv_write, export_memo_jsonl, work_root)

        # 6) [xlsx]
        venv_xlsx = build_fresh_venv(work_root, "venv-xlsx")
        install_extra(venv_xlsx, wheel, "xlsx", dist_dir)
        xlsx_dir = xlsx_extra_smoke(venv_xlsx, fixtures["flat"], work_root)

        # 7) [write,xlsx]
        venv_write_xlsx = build_fresh_venv(work_root, "venv-write-xlsx")
        install_extra(venv_write_xlsx, wheel, "write,xlsx", dist_dir)
        write_xlsx_extra_smoke(venv_write_xlsx, xlsx_dir, work_root)

        # 8) [fast]
        venv_fast = build_fresh_venv(work_root, "venv-fast")
        install_extra(venv_fast, wheel, "fast", dist_dir)
        fast_extra_smoke(venv_fast, fixtures["flat"], work_root)

        # 9) [all] — includes the full release wheel smoke
        venv_all = build_fresh_venv(work_root, "venv-all")
        install_extra(venv_all, wheel, "all", dist_dir)
        all_extra_smoke(venv_all, wheel, REPO_ROOT, work_root)

        print("PYPI INSTALL SMOKE: PASS")
        return 0
    finally:
        if args.keep_temp:
            print(f"work directory kept: {work_root}")
        else:
            shutil.rmtree(work_root, ignore_errors=True)


if __name__ == "__main__":
    raise SystemExit(main())
