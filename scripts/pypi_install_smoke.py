"""PyPI-installation smoke for the optional-dependency split (stdlib only).

Builds (or reuses) a feature wheel and, in a series of FRESH virtual
environments outside the repository, validates the whole install contract:

- **base**        — `pip install <wheel>`: mandatory dependency set contains
  only dbfread (checked via importlib.metadata inventory), `import dbfbridge`
  loads no heavy dependency, and the full Direct Read surface works;
- **migration**   — base install: DBF → JSONL, DBF → JSON, DBF → CSV (stdlib
  and Python fallback engines; no orjson/polars installed);
- **negative**    — without [write]: `reconstruct_dbf` raises
  `OptionalDependencyMissingError` (code OPTIONAL_DEPENDENCY_MISSING) and
  leaves ZERO output artifacts; without [xlsx]: XLSX export fails typed
  before creating anything;
- **[write]**     — JSONL → DBF/FPT reconstruction plus verification;
- **[xlsx]**      — XLSX export; **[write,xlsx]** — XLSX → DBF reconstruction;
- **[fast]**      — orjson/polars importable and results logically identical
  to the fallback engines;
- **[all]**       — the full release wheel smoke (scripts/release_wheel_smoke.py)
  plus reconstruction and XLSX checks.

No PyPI token, no upload, no tag/release interaction: this is a local
install-verification harness.  Fixtures are synthetic and generated by this
script (the outer environment provides `dbf` for that preparation only).
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
import tempfile
import venv
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
REQUIRED_BASE_ABSENT = ("dbf", "openpyxl", "xlsxwriter", "orjson", "polars")

# ---------------------------------------------------------------------------
# tiny helpers (stdlib only)
# ---------------------------------------------------------------------------


class SmokeFailure(RuntimeError):
    """One smoke step failed; nothing is retried or hidden."""


def _run(command: list[str], *, cwd: Path | None = None) -> subprocess.CompletedProcess[str]:
    completed = subprocess.run(command, capture_output=True, text=True, cwd=cwd)
    if completed.returncode != 0:
        raise SmokeFailure(
            f"command failed ({completed.returncode}): {' '.join(command)}\n"
            f"--- stdout ---\n{completed.stdout[-4000:]}\n--- stderr ---\n{completed.stderr[-4000:]}"
        )
    return completed


def _venv_python(venv_dir: Path) -> Path:
    scripts = venv_dir / "Scripts" if sys.platform.startswith("win") else venv_dir / "bin"
    return scripts / "python.exe" if sys.platform.startswith("win") else scripts / "python"


def make_fresh_venv(parent: Path, name: str) -> Path:
    """Deprecated alias of :func:`build_fresh_venv` (kept for callers)."""
    return build_fresh_venv(parent, name)


def build_fresh_venv(root: Path, name: str) -> Path:
    directory = root / name
    builder = venv.EnvBuilder(with_pip=True, clear=True)
    builder.create(directory)
    return directory


def venv_python(venv_dir: Path) -> Path:
    scripts = venv_dir / "Scripts" if sys.platform.startswith("win") else venv_dir / "bin"
    return scripts / "python.exe" if sys.platform.startswith("win") else scripts / "python"


def pip_install(venv_dir: Path, *spec: str) -> None:
    _run(
        [
            str(venv_python(venv_dir)),
            "-m",
            "pip",
            "install",
            "--force-reinstall",
            "--disable-pip-version-check",
            "--no-input",
            *spec,
        ]
    )


def run_snippet(venv_dir: Path, code: str, *, cwd: Path | None = None) -> str:
    return _run([str(venv_python(venv_dir)), "-c", code], cwd=cwd).stdout


def snippet(venv_dir: Path, code: str, *, cwd: Path | None = None) -> str:
    stdout = _run([str(venv_python(venv_dir)), "-c", code], cwd=cwd).stdout
    for line in stdout.strip().splitlines():
        if line.strip():
            print(f"  [{venv_dir.name}] {line.strip()}")
    return stdout


# ---------------------------------------------------------------------------
# fixture preparation (outer environment; uses the `dbf` writer library)
# ---------------------------------------------------------------------------


def prepare_fixtures(work: Path) -> dict[str, Path]:
    try:
        import dbf  # noqa: F401 - preparation-only dependency
    except ImportError as exc:  # pragma: no cover - environment error
        raise SmokeFailure(
            "fixture preparation needs the `dbf` library in the OUTER environment"
        ) from exc

    flat = work / "fixtures" / "customers.dbf"
    flat.parent.mkdir(parents=True, exist_ok=True)
    table = dbf.Table(
        str(flat),
        field_specs="ID N(6,0); NAME C(30); CITY C(20); AMOUNT N(10,2)",
        dbf_type="vfp",
        codepage=0xC8,
    )
    table.open(mode=dbf.READ_WRITE)
    for index in range(1, 201):
        table.append(
            {
                "ID": index,
                "NAME": f"Klient {index} ąęłóńśćźż",
                "CITY": "Warszawa",
                "AMOUNT": round(index * 1.5, 2),
            }
        )
    table.close()

    memo = work / "fixtures" / "notes.dbf"
    memo_table = dbf.Table(
        str(memo),
        field_specs="ID N(6,0); NOTATKA M",
        dbf_type="vfp",
        codepage=0xC8,
    )
    memo_table.open(mode=dbf.READ_WRITE)
    for index in range(1, 51):
        memo_table.append({"ID": index, "NOTATKA": f"Mazovia memo {index}: żółw, książka, śliwka."})
    memo_table.close()
    return {"flat": flat, "memo": memo}


