class SmokeFailure(RuntimeError):
    """One smoke step failed; nothing is retried or hidden."""


def _run(command: list[str], *, cwd: Path | None = None) -> subprocess.CompletedProcess[str]:
    completed = subprocess.run(command, capture_output=True, text=True, cwd=cwd)
    if completed.returncode != 0:
        raise SmokeFailure(
            f"command failed ({completed.returncode}): {' '.join(command)}\n"
            f"--- stdout ---\n{completed.stdout[-4000:]}\n--- stderr ---\n{completed.stderr[-4000:]}"
        )
    return completed


def _venv_python(venv_dir: Path) -> Path:
    scripts = venv_dir / "Scripts" if sys.platform.startswith("win") else venv_dir / "bin"
    return scripts / "python.exe" if sys.platform.startswith("win") else scripts / "python"


def make_fresh_venv(parent: Path, name: str) -> Path:
    """Deprecated alias of :func:`build_fresh_venv` (kept for callers)."""
    return build_fresh_venv(parent, name)


def build_fresh_venv(root: Path, name: str) -> Path:
    directory = root / name
    builder = venv.EnvBuilder(with_pip=True, clear=True)
    builder.create(directory)
    return directory


def venv_python(venv_dir: Path) -> Path:
    scripts = venv_dir / "Scripts" if sys.platform.startswith("win") else venv_dir / "bin"
    return scripts / "python.exe" if sys.platform.startswith("win") else scripts / "python"


def pip_install(venv_dir: Path, *spec: str) -> None:
    _run(
        [
            str(venv_python(venv_dir)),
            "-m",
            "pip",
            "install",
            "--force-reinstall",
            "--disable-pip-version-check",
            "--no-input",
            *spec,
        ]
    )


def run_snippet(venv_dir: Path, code: str, *, cwd: Path | None = None) -> str:
    return _run([str(venv_python(venv_dir)), "-c", code], cwd=cwd).stdout


def snippet(venv_dir: Path, code: str, *, cwd: Path | None = None) -> str:
    stdout = _run([str(venv_python(venv_dir)), "-c", code], cwd=cwd).stdout
    for line in stdout.strip().splitlines():
        if line.strip():
            print(f"  [{venv_dir.name}] {line.strip()}")
    return stdout


