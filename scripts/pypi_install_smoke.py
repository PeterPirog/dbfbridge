def write_extra_smoke(venv_dir: Path, export_dir: Path, work: Path) -> None:
    code = f"""
from pathlib import Path
from dbfbridge import reconstruct_dbf, verify_conversion

out = Path("write_out")
result = reconstruct_dbf(r"{str(export_dir).replace(chr(92), "/")}", str(out), input_format="jsonl", overwrite=True)
result.raise_for_errors()
dbfs = list(out.rglob("*.dbf"))
assert dbfs, "reconstructed DBF missing"
print("write OK")
"""
    snippet(venv_dir, code, cwd=work)


